"""Build eval/RESULTS.md from the JSON produced by the evaluation scripts.

Run everything fresh with:

    python week1_baseline/build_dataset.py
    python week1_baseline/train_baseline.py
    python week2_deep_learning/train_mlp.py
    python week3_retrieval/evaluate_retrieval.py
    python eval/run_rag_eval.py
    python eval/run_agent_eval.py
    python eval/make_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "eval" / "results"
ARTIFACTS = ROOT / "artifacts"


def load(path: Path) -> dict | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def main() -> None:
    week1 = load(ARTIFACTS / "metrics_week1.json")
    week2 = load(ARTIFACTS / "metrics_week2.json")
    retrieval = load(RESULTS / "retrieval.json")
    rag = load(RESULTS / "rag.json")
    agent = load(RESULTS / "agent.json")

    lines = [
        "# Evaluation results",
        "",
        "Generated by `eval/make_report.py` from the JSON files in `eval/results/`.",
        "Every number here came from a run on this machine; nothing is estimated.",
        "",
        "## Week 1-2: topic routing",
        "",
        "| Model | Template holdout accuracy | Hand-written accuracy (40) | Macro F1 (hand-written) |",
        "| --- | --- | --- | --- |",
    ]
    if week1:
        lines.append(
            f"| TF-IDF + logistic regression (shipped) | {week1['eval']['template_dev']['accuracy']:.3f} "
            f"| {week1['eval']['handwritten_40']['accuracy']:.3f} "
            f"| {week1['eval']['handwritten_40']['macro_f1']:.3f} |"
        )
    if week2:
        lines.append(
            f"| TF-IDF + MLP (128, 64) | {week2['eval']['template_dev']['accuracy']:.3f} "
            f"| {week2['eval']['handwritten_40']['accuracy']:.3f} "
            f"| {week2['eval']['handwritten_40']['macro_f1']:.3f} |"
        )
    lines += [
        "",
        "Both models score perfectly on templated questions and neither does on",
        "questions a person wrote. The MLP does not beat the baseline, so the",
        "simpler model is the one that ships.",
        "",
        "## Week 3: retrieval",
        "",
    ]
    if retrieval:
        lines += [
            f"Corpus: {retrieval['corpus']['chunks']} chunks from "
            f"{retrieval['corpus']['documents']} documents, "
            f"{retrieval['corpus']['avg_chunk_chars']} characters on average.",
            "",
            "| Retriever | Recall@1 | Recall@3 | Recall@5 | MRR |",
            "| --- | --- | --- | --- | --- |",
        ]
        for name, metrics in retrieval["retrievers"].items():
            marker = " *(shipped)*" if name == retrieval["shipped"] else ""
            lines.append(
                f"| {name}{marker} | {metrics['recall@1']:.3f} | {metrics['recall@3']:.3f} "
                f"| {metrics['recall@5']:.3f} | {metrics['mrr']:.3f} |"
            )
        lines += [
            "",
            "Every retriever finds a relevant document in the top 5 for all 13",
            "answerable questions. Rank 1 is where they differ.",
            "",
        ]

    if rag:
        summary = rag["summary"]
        lines += [
            "## Week 4: answer quality (15 held-out questions)",
            "",
            f"Mode: `{summary['mode']}`, model `{summary['model']}`, retriever `{summary['retriever']}`.",
            "",
            "| Metric | Result |",
            "| --- | --- |",
            f"| Retrieval hit rate (gold doc used) | {summary['retrieval_hit_rate']:.3f} |",
            f"| Answer contains the expected fact | {summary['answer_fact_rate']:.3f} ({summary['answer_fact_count']}) |",
            f"| Refusal behaviour correct | {summary['refusal_accuracy']:.3f} ({summary['refusal_count']}) |",
            f"| Unanswerable questions refused | {summary['unanswerable_refused']} |",
            f"| Answers with numbers not in the context | {summary['ungrounded_answers']} |",
            f"| Average latency | {summary['avg_latency_ms']} ms |",
            f"| Total cost for the run | ${summary['total_cost_usd']:.6f} |",
            "",
            "### Per-question results",
            "",
            "| # | Type | Question | Fact found | Refused | Sources |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for row in rag["rows"]:
            fact = "-" if row["keyword_ok"] is None else ("yes" if row["keyword_ok"] else "**no**")
            lines.append(
                f"| {row['id']} | {row['type']} | {row['question'][:58]} | {fact} "
                f"| {'yes' if row['refused'] else 'no'} | {len(row['sources'])} |"
            )
        lines.append("")

    if agent:
        s = agent["summary"]
        lines += [
            "## Week 4: agent (10 end-to-end cases)",
            "",
            "| Metric | Result |",
            "| --- | --- |",
            f"| Cases passing all checks | {s['passed']}/{s['cases']} ({s['pass_rate']:.1%}) |",
            f"| Correct tool selection | {s['tool_selection_accuracy']:.3f} |",
            f"| Answer contains expected fact | {s['fact_accuracy']:.3f} |",
            f"| Refusal behaviour correct | {s['refusal_accuracy']:.3f} |",
            f"| Average steps per run | {s['avg_steps']} |",
            f"| Average latency | {s['avg_latency_ms']} ms |",
            f"| MCP transport connected | {s['mcp_connected']} |",
            "",
            "| # | Question | Tools called | Passed |",
            "| --- | --- | --- | --- |",
        ]
        for row in agent["rows"]:
            passed = row["tools_ok"] and row["facts_ok"] is not False and row["refusal_ok"]
            lines.append(
                f"| {row['id']} | {row['text'][:58]} | {', '.join(row['tools_called']) or 'none'} "
                f"| {'yes' if passed else '**no**'} |"
            )
        lines.append("")

    out = ROOT / "eval" / "RESULTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
